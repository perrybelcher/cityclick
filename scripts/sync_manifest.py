#!/usr/bin/env python3
"""Synchronize src/data/index-manifest.json, public/_redirects, and src/config/slugMigrations.ts
deterministically from src/data/cities/{state}.json and scripts/slug_migrations.json.

Ensures 100% parity between primary-sourced city records and index-manifest entries for:
  - slug, name, stateCode, stateName
  - population, popChange2020to2023Pct, medianHouseholdIncome
  - medianHomeValue, medianGrossRent, effectivePropertyTaxRatePct
  - combinedSalesTaxRate (STRICTLY when permitsAndTax.provenance exists; purged otherwise!)
  - timeZone (from executiveTravel.timeZoneAbbr — never a hardcoded default)
  - topUnderservedNaics (up to 3 lowest saturationIndex underserved trade labels)
  - certified (True strictly for the 25 featured flagship slugs)

Purges all fabricated V1 fleet fields (reportedRetailRentSqFtYr, overallViability,
purchasingPower, growthMomentum, popGrowth5YrPct) across all 1,501 cities.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any, Dict, List

ROOT = Path(__file__).resolve().parent.parent
SCRIPT_DIR = Path(__file__).resolve().parent
CITIES_DIR = ROOT / "src" / "data" / "cities"
MANIFEST_PATH = ROOT / "src" / "data" / "index-manifest.json"
SLUG_MIGRATIONS_JSON = SCRIPT_DIR / "slug_migrations.json"
PUBLIC_REDIRECTS_PATH = ROOT / "public" / "_redirects"
TS_MIGRATIONS_PATH = ROOT / "src" / "config" / "slugMigrations.ts"

CERTIFIED_SLUGS = {
    "tx/austin",
    "ar/hot-springs-village",
    "ar/hot-springs",
    "id/boise",
    "fl/tampa",
    "az/scottsdale",
    "tn/nashville",
    "ok/oklahoma-city",
    "tx/dallas",
    "tx/houston",
    "tx/san-antonio",
    "az/phoenix",
    "nc/charlotte",
    "nc/raleigh",
    "fl/orlando",
    "fl/miami",
    "fl/jacksonville",
    "co/denver",
    "nv/las-vegas",
    "ut/salt-lake-city",
    "ga/atlanta",
    "ar/little-rock",
    "ar/fayetteville",
    "ar/bentonville",
    "al/huntsville",
}

LEGACY_STATIC_SLUG_REDIRECTS = {
    "ok/oklahoma": "ok/oklahoma-city",
    "ok/midwest": "ok/midwest-city",
    "tn/nashville-davidson-metropolitan-government-balance": "tn/nashville",
    "in/indianapolis-balance": "in/indianapolis",
    "ky/louisville-jefferson-county-metro-government-balance": "ky/louisville",
    "ga/augusta-richmond-county-consolidated-government-balance": "ga/augusta",
    "ga/athens-clarke-county-unified-government-balance": "ga/athens",
    "ct/milford-balance": "ct/milford",
    "mt/butte-silver-bow-balance": "mt/butte",
    "ut/salt-lake": "ut/salt-lake-city",
}

FABRICATED_V1_MANIFEST_KEYS = (
    "reportedRetailRentSqFtYr",
    "overallViability",
    "purchasingPower",
    "growthMomentum",
    "popGrowth5YrPct",
)


def load_slug_migrations() -> Dict[str, str]:
    merged = dict(LEGACY_STATIC_SLUG_REDIRECTS)
    if SLUG_MIGRATIONS_JSON.is_file():
        loaded = json.loads(SLUG_MIGRATIONS_JSON.read_text(encoding="utf-8"))
        if isinstance(loaded, dict):
            for k, v in loaded.items():
                if k and v and k != v:
                    merged[str(k)] = str(v)
    return dict(sorted(merged.items()))


def load_all_city_records() -> Dict[str, Dict[str, Any]]:
    records: Dict[str, Dict[str, Any]] = {}
    for p in sorted(CITIES_DIR.glob("*.json")):
        arr = json.loads(p.read_text(encoding="utf-8"))
        if not isinstance(arr, list):
            continue
        for c in arr:
            if isinstance(c, dict) and c.get("slug"):
                records[str(c["slug"])] = c
    return records


def compute_top_underserved(industries: List[Dict[str, Any]]) -> List[str]:
    underserved = [
        ind
        for ind in industries
        if isinstance(ind, dict) and ind.get("status") == "underserved" and ind.get("label")
    ]
    underserved.sort(key=lambda x: (x.get("saturationIndex", 9999), x.get("per10kResidents", 9999)))
    return [str(ind["label"]) for ind in underserved[:3]]


def write_redirects_and_ts(migrations: Dict[str, str]) -> None:
    lines = [
        "# Canonical Host & HTTPS Enforcement (www -> apex 301)",
        "https://www.cityclick.com/* https://cityclick.com/:splat 301",
        "http://www.cityclick.com/* https://cityclick.com/:splat 301",
        "http://cityclick.com/* https://cityclick.com/:splat 301",
        "",
        "# Normalized Census Place Slug 301 Redirects",
    ]
    for old_slug, new_slug in migrations.items():
        lines.append(f"/{old_slug}/ /{new_slug}/ 301")
        lines.append(f"/{old_slug} /{new_slug}/ 301")

    PUBLIC_REDIRECTS_PATH.write_text("\n".join(lines) + "\n", encoding="utf-8")

    ts_lines = [
        "// Auto-generated by scripts/sync_manifest.py — legacy V1 Census slug -> canonical normalized slug",
        "export const SLUG_MIGRATIONS: Record<string, string> = "
        + json.dumps(migrations, indent=2, ensure_ascii=False)
        + ";",
        "",
    ]
    TS_MIGRATIONS_PATH.write_text("\n".join(ts_lines), encoding="utf-8")


def build_manifest_entry(slug: str, c: Dict[str, Any]) -> Dict[str, Any]:
    demo = c.get("demographics") or {}
    htax = c.get("housingAndTaxes") or {}
    ptax = c.get("permitsAndTax") or {}
    et = c.get("executiveTravel") or {}

    entry: Dict[str, Any] = {
        "slug": slug,
        "name": c["name"],
        "stateCode": c["stateCode"],
        "stateName": c["stateName"],
        "population": demo.get("population"),
        "popChange2020to2023Pct": demo.get("popChange2020to2023Pct"),
        "medianHouseholdIncome": demo.get("medianHouseholdIncome"),
        "medianHomeValue": htax.get("medianHomeValue") if htax.get("medianHomeValue") is not None else demo.get("medianHomeValue"),
        "medianGrossRent": htax.get("medianGrossRent") if htax.get("medianGrossRent") is not None else demo.get("medianGrossRent"),
        "effectivePropertyTaxRatePct": htax.get("effectivePropertyTaxRatePct"),
        "topUnderservedNaics": compute_top_underserved(c.get("industries") or []),
        "certified": slug in CERTIFIED_SLUGS,
    }
    if ptax.get("combinedSalesTaxRate") is not None and ptax.get("provenance"):
        entry["combinedSalesTaxRate"] = ptax["combinedSalesTaxRate"]
    if et.get("timeZoneAbbr"):
        entry["timeZone"] = et["timeZoneAbbr"]
    return entry


def main() -> int:
    migrations = load_slug_migrations()
    city_map = load_all_city_records()
    old_manifest: List[Dict[str, Any]] = json.loads(MANIFEST_PATH.read_text(encoding="utf-8"))

    new_manifest: List[Dict[str, Any]] = []
    seen_slugs: set[str] = set()

    for entry in old_manifest:
        slug = str(entry.get("slug") or "")
        if slug in migrations and slug not in city_map and migrations[slug] in city_map:
            slug = migrations[slug]
        if slug in seen_slugs or slug not in city_map:
            continue
        seen_slugs.add(slug)
        new_manifest.append(build_manifest_entry(slug, city_map[slug]))

    for slug in sorted(set(city_map.keys()) - seen_slugs):
        seen_slugs.add(slug)
        new_manifest.append(build_manifest_entry(slug, city_map[slug]))

    MANIFEST_PATH.write_text(json.dumps(new_manifest, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    write_redirects_and_ts(migrations)

    with_tax = sum(1 for e in new_manifest if e.get("combinedSalesTaxRate") is not None)
    print(
        f"Synchronized {len(new_manifest)} primary-sourced manifest entries "
        f"({len(CERTIFIED_SLUGS)} featured flagships, {with_tax} with verified sales tax, "
        f"{len(migrations)} 301 slug redirects written to public/_redirects & src/config/slugMigrations.ts)."
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
